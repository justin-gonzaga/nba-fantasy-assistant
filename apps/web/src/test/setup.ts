import '@testing-library/jest-dom/vitest'

// jsdom has no matchMedia: default to a phone-sized window (tests opt into desktop by stubbing it).
if (!window.matchMedia) {
  window.matchMedia = (query: string) =>
    ({
      matches: false,
      media: query,
      onchange: null,
      addEventListener: () => {},
      removeEventListener: () => {},
      addListener: () => {},
      removeListener: () => {},
      dispatchEvent: () => false,
    }) as MediaQueryList
}
